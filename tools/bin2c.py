#!/usr/bin/env python3
"""Writes a binary file as a C array: const uint8_t <name>[] and const uint32_t <name>_size.

Usage: bin2c.py <input> <name> <output.c>
"""
import sys


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, name, out = sys.argv[1:]
    with open(src, "rb") as f:
        data = f.read()
    lines = [", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    with open(out, "w", newline="\n") as f:
        f.write("/* Generated by tools/bin2c.py from %s: do not edit */\n" % src)
        f.write("#include <stdint.h>\n\n")
        f.write("const uint8_t %s[] = {\n    %s\n};\n" % (name, ",\n    ".join(lines)))
        f.write("const uint32_t %s_size = %d;\n" % (name, len(data)))


if __name__ == "__main__":
    main()
